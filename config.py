# ---------------------------------------------------------------------------
# Reproducibility
# ---------------------------------------------------------------------------

SEED = 42


def set_seeds(seed: int = SEED) -> None:
    """
    Set random seeds for Python, NumPy, and PyTorch (CPU and GPU) and put
    cuDNN into deterministic mode.

    Deterministic cuDNN trades a little throughput for run-to-run
    reproducibility, which matters more here than raw training speed. Note
    that the LLaMA narrative text is generated by the Ollama runtime and is
    only partially controlled by the seed passed in src/models/llama.py.
    """
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)
    torch.backends.cudnn.deterministic = True
    torch.backends.cudnn.benchmark = False


def seeded_generator(seed: int = SEED) -> torch.Generator:
    """Return a torch.Generator seeded for DataLoader shuffling / splits."""
    return torch.Generator().manual_seed(seed)


