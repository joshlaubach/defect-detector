# The agent has an explicit "stop" action (index GRID_SIZE^2). Stopping ends
# the episode and pays a terminal bonus proportional to the fraction of the
# image's defects already found, minus a penalty for each known defective
# patch left un-inspected. Together these make stopping worthwhile only once
# recall is already high -- which is what turns "patch selection" into a real
# adaptive decision instead of a fixed sweep.
DQN_STOP_BONUS = 3.0            # terminal reward at recall = 1.0
DQN_MISS_PENALTY = 1.0          # subtracted per defective patch missed at stop
DQN_MAX_INSPECT_BUDGET = 40     # inference hard cap if the agent never stops


